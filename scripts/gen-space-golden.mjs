#!/usr/bin/env node
// Generates the C++ ABI golden vectors using space/js/abi.mjs (the JS twin
// ABI) as the oracle. Each output line is "in:<hex> out:<hex>" where <hex>
// is 16 hex chars per int64 slot. The native C++ test runner replays these
// lines and asserts identical output, so the twin and the C++ port cannot
// silently drift. Deterministic: seeds derive from the file index.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import * as abi from '../space/js/abi.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const GOLDEN = join(ROOT, 'space', 'cpp', 'test', 'golden');

// xorshift32. Fast, deterministic, sufficient for test inputs; no crypto use.
function prng(seedNum) {
  let s = (seedNum >>> 0) || 1;
  return () => {
    s ^= s << 13; s >>>= 0;
    s ^= s >> 17;
    s ^= s << 5; s >>>= 0;
    return s;
  };
}
function randInt(rng, lo, hi) { return lo + (rng() % (hi - lo + 1)); }

function toHex16(v) { return BigInt.asUintN(64, v).toString(16).padStart(16, '0'); }
function toHexStr(arr) { return arr.map(toHex16).join(''); }

function oneVector(fnName, input) {
  const scratch = new BigInt64Array(abi.SCRATCH_SLOTS);
  for (let i = 0; i < input.length; i++) scratch[i] = input[i];
  const outLen = abi[fnName](scratch, input.length);
  if (outLen < 0) throw new Error(`${fnName} returned ${outLen}`);
  const output = Array.from(scratch.slice(input.length, input.length + outLen));
  return `in:${toHexStr(input)} out:${toHexStr(output)}`;
}

function header(label) {
  return [
    `# Space ABI golden vectors: ${label}.`,
    '# Format: in:<hex> out:<hex>',
    '# Generated by scripts/gen-space-golden.mjs — do not edit by hand.',
  ];
}

function genMeasure(rng) {
  const lines = header('measure_text');
  for (let t = 0; t < 30; t++) {
    const family = BigInt(randInt(rng, 0, 1));
    const fontSize = BigInt(randInt(rng, 6, 24) * 100);
    const nChars = randInt(rng, 0, 20);
    const cps = [];
    for (let i = 0; i < nChars; i++) cps.push(BigInt(randInt(rng, 0x20, 0x7E)));
    lines.push(oneVector('space_measure_text',
      [1n, family, fontSize, BigInt(nChars), ...cps]));
  }
  return lines.join('\n') + '\n';
}

function genApportion(rng) {
  const lines = header('apportion');
  for (let t = 0; t < 30; t++) {
    const total = BigInt(randInt(rng, 10, 100000));
    const n = randInt(rng, 1, 8);
    const weights = [];
    for (let i = 0; i < n; i++) weights.push(BigInt(randInt(rng, 1, 1000)));
    lines.push(oneVector('space_apportion', [1n, total, BigInt(n), ...weights]));
  }
  return lines.join('\n') + '\n';
}

function genClaim(rng) {
  const lines = header('claim_combine');
  for (let t = 0; t < 20; t++) {
    const op = BigInt(randInt(rng, 0, 2));
    const a = [
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 2000)),
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 2000)),
      BigInt(randInt(rng, 0, 50)),   BigInt(randInt(rng, 1, 15)),
    ];
    const b = [
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 2000)),
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 2000)),
      BigInt(randInt(rng, 0, 50)),   BigInt(randInt(rng, 1, 15)),
    ];
    lines.push(oneVector('space_claim_combine', [1n, op, ...a, ...b]));
  }
  return lines.join('\n') + '\n';
}

function genPaginate(rng) {
  const lines = header('paginate');
  for (let t = 0; t < 30; t++) {
    const arch = BigInt(randInt(rng, 0, 8));
    const shape = BigInt(randInt(rng, 0, 3));
    const rows = BigInt(randInt(rng, 0, 200));
    lines.push(oneVector('space_paginate', [1n, arch, shape, rows]));
  }
  return lines.join('\n') + '\n';
}

function genAnchor(rng) {
  const lines = header('anchor');
  for (let t = 0; t < 20; t++) {
    const oldRect = [
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)),
      BigInt(randInt(rng, 100, 2000)), BigInt(randInt(rng, 100, 2000)),
    ];
    const oldScale = [BigInt(randInt(rng, 1, 100)), BigInt(randInt(rng, 1, 100))];
    const anchorPage = [BigInt(randInt(rng, 0, 500)), BigInt(randInt(rng, 0, 500))];
    const newRect = [
      BigInt(randInt(rng, 0, 1000)), BigInt(randInt(rng, 0, 1000)),
      BigInt(randInt(rng, 100, 2000)), BigInt(randInt(rng, 100, 2000)),
    ];
    const newScale = [BigInt(randInt(rng, 1, 100)), BigInt(randInt(rng, 1, 100))];
    const tol = BigInt(randInt(rng, 0, 500));
    lines.push(oneVector('space_anchor', [
      1n, ...oldRect, ...oldScale, ...anchorPage, ...newRect, ...newScale, tol,
      1280n * 75n, 720n * 75n,
    ]));
  }
  return lines.join('\n') + '\n';
}

function genSolve(rng) {
  const lines = header('solve');
  for (let t = 0; t < 20; t++) {
    const vw = BigInt(randInt(rng, 800, 2000)) * 75n;
    const vh = BigInt(randInt(rng, 600, 1500)) * 75n;
    const n = randInt(rng, 1, 3);
    const panes = [];
    for (let i = 0; i < n; i++) {
      panes.push(BigInt(randInt(rng, 0, 6)));    // archetype
      panes.push(0n);                             // isBar
      panes.push(BigInt(randInt(rng, 0, 30)));   // rowsUpper
      panes.push(1n);                             // weight
    }
    lines.push(oneVector('space_solve', [1n, vw, vh, BigInt(n), ...panes]));
  }
  return lines.join('\n') + '\n';
}

function main() {
  mkdirSync(GOLDEN, { recursive: true });
  const specs = [
    ['measure.txt', genMeasure],
    ['apportion.txt', genApportion],
    ['claim.txt', genClaim],
    ['paginate.txt', genPaginate],
    ['anchor.txt', genAnchor],
    ['solve.txt', genSolve],
  ];
  for (let i = 0; i < specs.length; i++) {
    const [name, gen] = specs[i];
    const rng = prng(0xC0FFEE + i);
    const content = gen(rng);
    writeFileSync(join(GOLDEN, name), content);
    const count = content.split('\n').filter((l) => l.startsWith('in:')).length;
    console.log(`gen:space-golden: ${name} (${count} vectors)`);
  }
}

main();
