#!/usr/bin/env node
// Generates attention/cpp/test/golden/*.txt using attention/js/abi.mjs as
// the oracle. Deterministic seeds. The native runner replays these; the JS
// parity test replays the same files against the twin, so both ends of the
// ABI are checked against the same reference.
import { writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { join } from 'node:path';
import * as abi from '../attention/js/abi.mjs';
import { loadLevels } from '../attention/js/levels.mjs';
import { makeState, step as twinStep } from '../attention/js/machine.mjs';

const ROOT = fileURLToPath(new URL('..', import.meta.url));
const GOLDEN = join(ROOT, 'attention', 'cpp', 'test', 'golden');

function prng(seedNum) {
  let s = (seedNum >>> 0) || 1;
  return () => { s ^= s << 13; s >>>= 0; s ^= s >> 17; s ^= s << 5; s >>>= 0; return s; };
}
function randInt(rng, lo, hi) { return lo + (rng() % (hi - lo + 1)); }

function toHex16(v) { return BigInt.asUintN(64, v).toString(16).padStart(16, '0'); }
function toHexStr(arr) { return arr.map(toHex16).join(''); }

function oneVector(fnName, input) {
  const scratch = new BigInt64Array(abi.ATT_SCRATCH_SLOTS);
  for (let i = 0; i < input.length; i++) scratch[i] = input[i];
  const outLen = abi[fnName](scratch, input.length);
  if (outLen < 0) {
    // Encode error codes as a single int64 output ("errcode"), so the
    // native side can compare without a special-case branch.
    return `in:${toHexStr(input)} out:${toHexStr([BigInt(outLen)])}`;
  }
  const output = Array.from(scratch.slice(input.length, input.length + outLen));
  return `in:${toHexStr(input)} out:${toHexStr(output)}`;
}

function header(label) {
  return [
    `# Attention ABI golden vectors: ${label}.`,
    '# Format: in:<hex> out:<hex>',
    '# Generated by scripts/gen-attention-golden.mjs — do not edit by hand.',
  ];
}

function genLevels() {
  const lines = header('levels_table');
  for (const theme of [0n, 1n]) {
    lines.push(oneVector('att_levels_table', [1n, theme]));
  }
  return lines.join('\n') + '\n';
}

function genValidate() {
  const lines = header('validate');
  const L = loadLevels();
  for (const theme of ['light', 'dark']) {
    const t = L.themes[theme];
    const input = [1n];
    for (let l = 0; l < 3; l++) {
      const r = t.table[l];
      input.push(BigInt(r.opacity), BigInt(r.brightness), BigInt(r.saturation),
        BigInt(r.blur), BigInt(r.shadow), BigInt(r.radius));
    }
    input.push(BigInt(t.fg.r), BigInt(t.fg.g), BigInt(t.fg.b));
    input.push(BigInt(t.bg.r), BigInt(t.bg.g), BigInt(t.bg.b));
    input.push(BigInt(L.timing.durationMs.focus), BigInt(L.timing.durationMs.inputBegin),
      BigInt(L.timing.durationMs.inputEnd), BigInt(L.timing.durationMs.transfer));
    input.push(BigInt(L.timing.easing.x1), BigInt(L.timing.easing.y1),
      BigInt(L.timing.easing.x2), BigInt(L.timing.easing.y2));
    lines.push(oneVector('att_validate', input));
  }
  return lines.join('\n') + '\n';
}

// Encode a JS state as the ABI's flat <state> layout.
function encodeState(state) {
  const out = [];
  function emitId(id) {
    out.push(BigInt([...id].length));
    for (const ch of id) out.push(BigInt(ch.codePointAt(0)));
  }
  function emitRing(ring) {
    out.push(BigInt(ring.length));
    for (const a of ring) {
      emitId(a.id);
      out.push(BigInt({ DOC: 0, FORM: 1, TRAIL: 2, BAR: 3 }[a.kind]));
    }
  }
  function emitHist(history) {
    out.push(BigInt(history.length));
    for (const ring of history) emitRing(ring);
  }
  function emitBasic(snap) {
    emitRing(snap.ring);
    emitHist(snap.history);
    out.push(BigInt(snap.lastPointerEpoch));
  }
  function emitFull(snap) {
    emitRing(snap.ring);
    emitHist(snap.history);
    out.push(BigInt(snap.lastPointerEpoch));
    if (snap.transfer) {
      out.push(1n);
      emitId(snap.transfer.sourceId);
      out.push(BigInt({ entry: 0, rows: 1, row: 2, period: 3, node: 4 }[snap.transfer.payloadKind]));
      emitBasic(snap.transfer.snapshot);
    } else { out.push(0n); }
  }
  out.push(BigInt(state.lastPointerEpoch));
  emitRing(state.ring);
  emitHist(state.history);
  if (state.transfer) {
    out.push(1n);
    emitId(state.transfer.sourceId);
    out.push(BigInt({ entry: 0, rows: 1, row: 2, period: 3, node: 4 }[state.transfer.payloadKind]));
    emitBasic(state.transfer.snapshot);
  } else { out.push(0n); }
  if (state.input) {
    out.push(1n);
    out.push(BigInt({ text: 0, voice: 1, document: 2 }[state.input.channel]));
    emitFull(state.input.snapshot);
  } else { out.push(0n); }
  return out;
}

function encodeEvent(e) {
  const out = [];
  function emitId(id) {
    out.push(BigInt([...id].length));
    for (const ch of id) out.push(BigInt(ch.codePointAt(0)));
  }
  switch (e.type) {
    case 'OPEN': out.push(0n); emitId(e.actor.id); out.push(BigInt({ DOC: 0, FORM: 1, TRAIL: 2 }[e.actor.kind])); break;
    case 'CLOSE': out.push(1n); emitId(e.id); break;
    case 'FOCUS': {
      out.push(2n); emitId(e.id);
      out.push(BigInt({ pointer: 0, keyboard: 1, command: 2, programmatic: 3 }[e.source]));
      if (e.source === 'pointer') out.push(BigInt(e.pointerEpoch));
      break;
    }
    case 'INPUT_BEGIN': out.push(3n); out.push(BigInt({ text: 0, voice: 1, document: 2 }[e.channel])); break;
    case 'INPUT_END': out.push(4n); out.push(BigInt({ commit: 0, cancel: 1 }[e.outcome])); break;
    case 'TRANSFER_COPY': out.push(5n); emitId(e.sourceId); out.push(BigInt({ entry: 0, rows: 1, row: 2, period: 3, node: 4 }[e.payloadKind])); break;
    case 'TRANSFER_PASTE': out.push(6n); emitId(e.targetId); out.push(BigInt({ impact: 0, 'draft-entry': 1, 'draft-lines': 2, 'trail-edit': 3, 'period-change': 4 }[e.outcomeKind])); break;
    case 'TRANSFER_CANCEL': out.push(7n); break;
    case 'BACK': out.push(8n); break;
    case 'RESIZE': out.push(9n); break;
  }
  return out;
}

function genStep(rng) {
  const lines = header('step');
  const scenarios = [
    { name: 'empty', state: makeState({ actors: [] }) },
    { name: 'one',   state: makeState({ actors: [{ id: 'A', kind: 'DOC' }] }) },
    { name: 'three', state: makeState({ actors: [
      { id: 'A', kind: 'DOC' }, { id: 'B', kind: 'DOC' }, { id: 'C', kind: 'DOC' },
    ] }) },
    { name: 'trail', state: makeState({ actors: [
      { id: 'BS', kind: 'DOC' }, { id: 'CF', kind: 'DOC' },
      { id: 'TR', kind: 'TRAIL' }, { id: 'FM', kind: 'FORM' },
    ] }) },
  ];
  const events = [
    { type: 'OPEN', actor: { id: 'N', kind: 'DOC' } },
    { type: 'CLOSE', id: 'A' },
    { type: 'FOCUS', id: 'B', source: 'command' },
    { type: 'FOCUS', id: 'C', source: 'pointer', pointerEpoch: 5 },
    { type: 'INPUT_BEGIN', channel: 'text' },
    { type: 'INPUT_END', outcome: 'commit' },
    { type: 'INPUT_END', outcome: 'cancel' },
    { type: 'TRANSFER_COPY', sourceId: 'A', payloadKind: 'rows' },
    { type: 'TRANSFER_PASTE', targetId: 'B', outcomeKind: 'draft-lines' },
    { type: 'TRANSFER_CANCEL' },
    { type: 'BACK' },
    { type: 'RESIZE' },
  ];
  for (const sc of scenarios) {
    for (const ev of events) {
      const stateEnc = encodeState(sc.state);
      const evtEnc = encodeEvent(ev);
      const input = [1n, BigInt(stateEnc.length), ...stateEnc, BigInt(evtEnc.length), ...evtEnc];
      lines.push(oneVector('att_step', input));
      // Advance state one step through the twin, so subsequent vectors are
      // realistic sequences rather than every event applied to the same
      // start. This exercises history, input restoration and transfer
      // cancel against the golden replay.
      sc.state = twinStep(sc.state, ev).state;
    }
  }
  return lines.join('\n') + '\n';
}

function main() {
  mkdirSync(GOLDEN, { recursive: true });
  const specs = [
    ['levels.txt', genLevels],
    ['validate.txt', genValidate],
    ['step.txt', (rng) => genStep(rng)],
  ];
  for (let i = 0; i < specs.length; i++) {
    const [name, gen] = specs[i];
    const content = gen(prng(0xA77E17 + i));
    writeFileSync(join(GOLDEN, name), content);
    const count = content.split('\n').filter((l) => l.startsWith('in:')).length;
    console.log(`gen:attention-golden: ${name} (${count} vectors)`);
  }
}

main();
