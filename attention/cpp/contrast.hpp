inline int32_t clamp_channel(int64_t c) {
    if (c < 0) return 0;
    if (c > 255) return 255;
    return (int32_t)c;
}

// Relative luminance in ppm. Rec. 709 coefficients scaled by 10000.
inline int32_t luminance_ppm(int64_t r, int64_t g, int64_t b) {
    int32_t R = clamp_channel(r), G = clamp_channel(g), B = clamp_channel(b);
    int64_t acc = 2126 * LINEAR_LUT[R] + 7152 * LINEAR_LUT[G] + 722 * LINEAR_LUT[B];
    // Divide by 10000 with rounding-half-up, matching the twin's Math.round.
    return (int32_t)((acc + 5000) / 10000);
}

// WCAG contrast ratio, permille. Both inputs are ppm; result is >= 1000.
inline int32_t contrast_permille(int32_t l1Ppm, int32_t l2Ppm) {
    int64_t light = imax(l1Ppm, l2Ppm);
    int64_t dark = imin(l1Ppm, l2Ppm);
    int64_t num = light + 50000;
    int64_t den = dark + 50000;
    return (int32_t)((num * 1000) / den);
}

// Blend one channel of fg toward bg by opacity * brightness / 1e6.
inline int32_t blend_channel(int64_t fg, int64_t bg, int32_t opacityPermille, int32_t brightnessPermille) {
    int64_t factor = (int64_t)opacityPermille * (int64_t)brightnessPermille; // 0..1e6
    int64_t f = clamp_channel(fg);
    int64_t b = clamp_channel(bg);
    return (int32_t)((b * (1000000 - factor) + f * factor) / 1000000);
}

// Effective fg colour (blend toward bg by opacity * brightness) then contrast
// ratio vs bg. This is the exact computation attention/js/contrast.mjs does
// in `levelContrastPermille`, and the value T3 validates against.
inline int32_t level_contrast_permille(
    int64_t fgR, int64_t fgG, int64_t fgB,
    int64_t bgR, int64_t bgG, int64_t bgB,
    int32_t opacityPermille, int32_t brightnessPermille) {
    int32_t r = blend_channel(fgR, bgR, opacityPermille, brightnessPermille);
    int32_t g = blend_channel(fgG, bgG, opacityPermille, brightnessPermille);
    int32_t b = blend_channel(fgB, bgB, opacityPermille, brightnessPermille);
    int32_t fgL = luminance_ppm(r, g, b);
    int32_t bgL = luminance_ppm(bgR, bgG, bgB);
    return contrast_permille(fgL, bgL);
}

